//! the lists that tie rust types to the ui.
//!
//! every settings section and every event the ui may see is named here once.
//! the lists register the sections at startup, and `cargo test` turns them
//! into `SettingsMap.ts` and `EventMap.ts` so the ui gets the same names and
//! payload types checked by the typescript compiler.

use vellum_core::settings::{AppearanceSettings, PerformanceSettings, SettingsStore};

macro_rules! settings_sections {
    ($($section:ty),* $(,)?) => {
        pub fn register_settings(store: &SettingsStore) {
            $(store.register::<$section>();)*
        }

        #[cfg(test)]
        fn settings_entries(cfg: &ts_rs::Config) -> Vec<(&'static str, String)> {
            use vellum_core::settings::SettingsSection;
            vec![$((<$section>::KEY, <$section as ts_rs::TS>::name(cfg))),*]
        }
    };
}

macro_rules! ui_events {
    ($($event:ty),* $(,)?) => {
        #[cfg(test)]
        fn event_entries(cfg: &ts_rs::Config) -> Vec<(&'static str, String)> {
            use vellum_core::event::Event;
            vec![$((<$event>::NAME, <$event as ts_rs::TS>::name(cfg))),*]
        }
    };
}

settings_sections![AppearanceSettings, PerformanceSettings];

ui_events![
    vellum_core::jobs::JobEvent,
    vellum_core::settings::SettingsChanged
];

#[cfg(test)]
mod tests {
    use std::collections::BTreeSet;
    use std::fs;

    use ts_rs::Config;

    use super::*;

    fn map_file(name: &str, doc: &str, entries: &[(&'static str, String)]) -> String {
        let types: BTreeSet<&str> = entries.iter().map(|(_, ty)| ty.as_str()).collect();
        let mut out = String::from("// generated by `cargo test`, do not edit by hand\n");
        for ty in types {
            out.push_str(&format!("import type {{ {ty} }} from \"./{ty}\";\n"));
        }
        out.push_str(&format!("\n/**\n * {doc}\n */\nexport type {name} = {{\n"));
        for (key, ty) in entries {
            out.push_str(&format!("  \"{key}\": {ty};\n"));
        }
        out.push_str("};\n");
        out
    }

    #[test]
    fn export_bindings_maps() {
        let cfg = Config::from_env();
        let dir = cfg.out_dir();
        fs::create_dir_all(dir).unwrap();

        let events = map_file(
            "EventMap",
            "every backend event by name",
            &event_entries(&cfg),
        );
        fs::write(dir.join("EventMap.ts"), events).unwrap();

        let settings = map_file(
            "SettingsMap",
            "every settings section by key",
            &settings_entries(&cfg),
        );
        fs::write(dir.join("SettingsMap.ts"), settings).unwrap();
    }

    #[test]
    fn names_are_unique() {
        let cfg = Config::from_env();
        for entries in [event_entries(&cfg), settings_entries(&cfg)] {
            let names: BTreeSet<_> = entries.iter().map(|(name, _)| *name).collect();
            assert_eq!(names.len(), entries.len());
        }
    }

    #[test]
    fn every_listed_section_is_registered() {
        let store = SettingsStore::in_memory(None);
        register_settings(&store);
        let keys: Vec<String> = store.all().into_keys().collect();
        let mut listed: Vec<_> = settings_entries(&Config::from_env())
            .into_iter()
            .map(|entry| entry.0)
            .collect();
        listed.sort_unstable();
        assert_eq!(keys, listed);
    }
}
